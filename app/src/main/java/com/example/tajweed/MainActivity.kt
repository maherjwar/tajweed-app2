class Store(c: Context) {
    private val ctx = c.applicationContext
    private val p = c.getSharedPreferences("progress", 0)
    var xp by mutableIntStateOf(p.getInt("xp", 0)); private set
    var streak by mutableIntStateOf(p.getInt("streak", 0)); private set
    var today by mutableIntStateOf(0); private set
    val stars = mutableStateListOf<Int>().apply { repeat(lessons.size) { add(p.getInt("s$it", 0)) } }
    val tests = mutableStateListOf<Int>().apply { repeat(unitStarts.size) { add(p.getInt("t$it", 0)) } }
    private val gaps = intArrayOf(0, 1, 3, 7, 14, 30)
    // نظام المراجعة المتباعدة: لكل مثال (صندوق، يوم الاستحقاق)
    val srs = mutableStateMapOf<String, Pair<Int, Long>>().apply {
        (p.getString("srs", "") ?: "").split("\n").forEach { line ->
            val parts = line.split(",", limit = 3)
            if (parts.size == 3) {
                val b = parts[0].toIntOrNull(); val dd = parts[1].toLongOrNull()
                if (b != null && dd != null) put(parts[2], b to dd)
            }
        }
        // ترحيل الأخطاء المحفوظة بالنظام القديم
        (p.getStringSet("miss", emptySet()) ?: emptySet()).forEach { if (!containsKey(it)) put(it, 0 to 0L) }
    }
    val misses: List<String> get() = srs.filter { it.value.second <= day() }.keys.toList()
    val att = mutableStateListOf<Int>().apply { repeat(lessons.size) { add(p.getInt("at$it", 0)) } }
    val cor = mutableStateListOf<Int>().apply { repeat(lessons.size) { add(p.getInt("co$it", 0)) } }
    var practiced by mutableIntStateOf(p.getInt("practiced", 0)); private set
    var challenges by mutableIntStateOf(p.getInt("chCount", 0)); private set
    var challengeDay by mutableLongStateOf(p.getLong("chDay", -1L)); private set
    val done get() = stars.indexOfFirst { it == 0 }.let { if (it < 0) stars.size else it }
    private fun day() = System.currentTimeMillis() / 86_400_000L
    var seen by mutableStateOf(p.getBoolean("seen", false)); private set

    private val systemDark = (c.resources.configuration.uiMode and Configuration.UI_MODE_NIGHT_MASK) == Configuration.UI_MODE_NIGHT_YES
    var dark by mutableStateOf(p.getBoolean("dark", systemDark)); private set
    var autoPlay by mutableStateOf(p.getBoolean("auto", true)); private set
    var sfx by mutableStateOf(p.getBoolean("sfx", true)); private set
    var speed by mutableFloatStateOf(p.getFloat("speed", 1f)); private set
    var remind by mutableStateOf(p.getBoolean("remind", false)); private set
    var hour by mutableIntStateOf(p.getInt("hour", 20)); private set

    init {
        today = if (p.getLong("dayKey", 0) == day()) p.getInt("dayXp", 0) else 0
        Pal.dark = dark
        Sfx.enabled = sfx
        if (remind) Reminder.schedule(ctx, hour)
    }

    fun markSeen() { seen = true; p.edit().putBoolean("seen", true).apply() }
    fun changeDark(v: Boolean) { dark = v; Pal.dark = v; p.edit().putBoolean("dark", v).apply() }
    fun changeSfx(v: Boolean) { sfx = v; Sfx.enabled = v; p.edit().putBoolean("sfx", v).apply() }
    fun changeAuto(v: Boolean) { autoPlay = v; p.edit().putBoolean("auto", v).apply() }
    fun changeSpeed(v: Float) { speed = v; p.edit().putFloat("speed", v).apply() }
    fun changeRemind(v: Boolean) {
        remind = v; p.edit().putBoolean("remind", v).apply()
        if (v) Reminder.schedule(ctx, hour) else Reminder.cancel(ctx)
    }
    fun changeHour(h: Int) {
        hour = (h + 24) % 24; p.edit().putInt("hour", hour).apply()
        if (remind) Reminder.schedule(ctx, hour)
    }

    private fun saveSrs() {
        p.edit().putString("srs", srs.entries.joinToString("\n") { "${it.value.first},${it.value.second},${it.key}" }).apply()
    }
    // الإجابة الصحيحة ترفع المثال صندوقًا وتبعد موعده، والخطأ يعيده للمراجعة اليوم
    fun srsAnswer(key: String, ok: Boolean) {
        if (key.isEmpty()) return
        val cur = srs[key]
        if (ok && cur != null && cur.second > day()) return
        val nb = if (ok) minOf((cur?.first ?: 0) + 1, 5) else 0
        srs[key] = nb to (day() + gaps[nb])
        saveSrs()
    }
    fun daysUntilReview(key: String): Int? = srs[key]?.let { (it.second - day()).toInt() }
    fun mastered(): Int = srs.count { it.value.first >= 4 }

    private fun gain(g: Int) {
        val d = day(); val last = p.getLong("last", 0)
        if (last != d) streak = if (last == d - 1) streak + 1 else 1
        today = if (p.getLong("dayKey", 0) == d) today + g else g
        xp += g
        p.edit().putInt("xp", xp).putInt("streak", streak).putInt("dayXp", today)
            .putLong("dayKey", d).putLong("last", d).apply()
    }
    fun finish(i: Int, s: Int, gained: Int) {
        gain(gained)
        if (s > stars[i]) stars[i] = s
        p.edit().putInt("s$i", stars[i]).apply()
    }
    fun finishTest(u: Int, s: Int) {
        gain(s * 15)
        if (s > tests[u]) tests[u] = s
        p.edit().putInt("t$u", tests[u]).apply()
    }
    fun reward(g: Int) = gain(g)

    fun record(key: String, ok: Boolean) {
        val i = lessons.indexOfFirst { it.title == key.substringBefore("|") }
        if (i < 0) return
        att[i] = att[i] + 1
        if (ok) cor[i] = cor[i] + 1
        p.edit().putInt("at$i", att[i]).putInt("co$i", cor[i]).apply()
    }
    fun accuracy(): Float = if (att.sum() == 0) 0f else cor.sum().toFloat() / att.sum()
    fun challengeDoneToday() = challengeDay == day()
    fun finishChallenge(s: Int) {
        val first = !challengeDoneToday()
        gain(if (first) s * 10 + 20 else 0)
        if (first) {
            challengeDay = day(); challenges++
            p.edit().putLong("chDay", challengeDay).putInt("chCount", challenges).apply()
        }
    }
    fun practiceDone(s: Int) {
        gain(s * 3); practiced++
        p.edit().putInt("practiced", practiced).apply()
    }

    // رمز نسخ احتياطي يمكن نقله يدويًا بين الأجهزة
    fun exportCode(): String {
        val o = JSONObject()
        for ((k, v) in p.all) {
            when (v) {
                is Boolean -> o.put(k, "b:$v")
                is Int -> o.put(k, "i:$v")
                is Long -> o.put(k, "l:$v")
                is Float -> o.put(k, "f:$v")
                is String -> o.put(k, "s:$v")
                is Set<*> -> o.put(k, JSONArray(v.map { it.toString() }))
            }
        }
        return "TJW1:" + Base64.encodeToString(o.toString().toByteArray(Charsets.UTF_8), Base64.NO_WRAP)
    }
    fun importCode(code: String): Boolean {
        val t = code.trim()
        if (!t.startsWith("TJW1:")) return false
        return try {
            val o = JSONObject(String(Base64.decode(t.removePrefix("TJW1:"), Base64.NO_WRAP), Charsets.UTF_8))
            val ed = p.edit().clear()
            o.keys().forEach { k ->
                val v = o.get(k)
                if (v is JSONArray) ed.putStringSet(k, (0 until v.length()).map { v.getString(it) }.toSet())
                else {
                    val str = v.toString(); val x = str.substring(2)
                    when (str.take(2)) {
                        "b:" -> ed.putBoolean(k, x.toBoolean())
                        "i:" -> ed.putInt(k, x.toInt())
                        "l:" -> ed.putLong(k, x.toLong())
                        "f:" -> ed.putFloat(k, x.toFloat())
                        else -> ed.putString(k, x)
                    }
                }
            }
            ed.commit()
        } catch (e: Exception) { false }
    }
}

