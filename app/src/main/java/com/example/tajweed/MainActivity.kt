data class Ques(
    val prompt: String, val verse: String, val opts: List<String>, val answers: Set<Int>, val why: String,
    val listen: Boolean = false, val hint: String = "", val key: String = "",
    val multi: Boolean = false, val marks: List<String> = emptyList()
) {
    val ans get() = answers.first()
}

data class Lesson(
    val title: String, val unit: String?, val intro: String, val ask: String,
    val opts: List<String>, val items: List<Triple<String, Int, String>>, val custom: List<Ques>? = null,
    val noun: String = "حكم"
) {
    private val letters get() = noun == "مخرج" || noun == "صفة"
    private val thing get() = if (letters) "الحرف" else "المثال"
    private fun one(v: String, a: Int, w: String, prompt: String = ask, listen: Boolean = false, hint: String = "") =
        Ques(prompt, v, opts, setOf(a), w, listen, hint, "$title|$v", false, markMap["$title|$v"] ?: emptyList())

    val qs get() = items.map { (v, a, w) -> one(v, a, w) }

    // أسئلة «استمع واختر»: تبدأ التلاوة تلقائيًا ثم يختار الحكم
    fun listen(): List<Ques> = items.filter { it.first in audioRefs }.shuffled().take(1).map { (v, a, w) ->
        one(v, a, w, "استمع إلى المثال «$v» ثم اختر الحكم (إن احتجت فاضغط تلميح)", true, intro)
    }

    // صح أم خطأ
    fun trueFalse(): List<Ques> {
        val (v, a, w) = items.random()
        val truth = Random.nextBoolean()
        val shown = if (truth) a else opts.indices.filter { it != a }.random()
        val why = (if (truth) "" else "الحكم الصحيح هو «${opts[a]}». ") + w
        return listOf(Ques("هل $noun هذا $thing «${opts[shown]}»؟", v, listOf("صحيح", "خطأ"),
            setOf(if (truth) 0 else 1), why, key = "$title|$v", marks = markMap["$title|$v"] ?: emptyList()))
    }

    // اختيار متعدد: اختر جميع الأمثلة التي فيها حكم معيّن
    fun multi(): List<Ques> {
        val groups = items.groupBy { it.second }
        val good = groups.filter { it.value.size >= 2 }.keys.toList()
        if (good.isEmpty()) return emptyList()
        val r = good.random()
        val right = groups[r]!!.shuffled().take(2)
        val wrong = items.filter { it.second != r }.shuffled().take(2)
        if (wrong.size < 2) return emptyList()
        val all = (right + wrong).shuffled()
        return listOf(Ques(if (letters) "اختر جميع الحروف التي ${noun}ها «${opts[r]}»" else "اختر جميع الأمثلة التي فيها «${opts[r]}»", "", all.map { it.first },
            all.indices.filter { all[it].second == r }.toSet(),
            right.joinToString("\n") { "• ${it.first}: ${it.third}" }, multi = true))
    }

    // أسئلة معكوسة: أعطيناك الحكم، اختر المثال
    fun reverse(): List<Ques> = qs.distinctBy { it.opts[it.ans] }.take(2).map { q ->
        val rule = q.opts[q.ans]
        val others = qs.filter { it.opts[it.ans] != rule }.map { it.verse }.distinct().shuffled().take(2)
        val o = (others + q.verse).shuffled()
        Ques(if (letters) "أيّ الحروف ${noun}ها «$rule»؟" else "أيّ الأمثلة فيها «$rule»؟", "", o, setOf(o.indexOf(q.verse)), "${q.verse}: ${q.why}", key = q.key)
    }
}

