@Composable
fun LessonScreen(l: Lesson, pl: Player, st: Store, perStar: Int, maxHearts: Int, onExit: (Int?) -> Unit) {
    val haptic = LocalHapticFeedback.current
    val queue = remember {
        mutableStateListOf<Ques>().apply {
            addAll(l.custom ?: (l.qs + l.listen() + l.trueFalse() + l.multi() + l.reverse()))
        }
    }
    var step by remember { mutableIntStateOf(-1) }
    var hearts by remember { mutableIntStateOf(maxHearts) }
    var sel by remember { mutableStateOf(setOf<Int>()) }
    var checked by remember { mutableStateOf(false) }
    var mistakes by remember { mutableIntStateOf(0) }
    var hint by remember { mutableStateOf(false) }
    val failed = remember { mutableSetOf<String>() }
    var combo by remember { mutableIntStateOf(0) }
    val shake = remember { Animatable(0f) }
    LaunchedEffect(mistakes) {
        if (mistakes > 0) {
            repeat(3) { shake.animateTo(14f, tween(50)); shake.animateTo(-14f, tween(50)) }
            shake.animateTo(0f, tween(50))
        }
    }
    LaunchedEffect(hearts, checked) { if (hearts == 0 && !checked) Sfx.lose() }
    val finished = step >= 0 && step >= queue.size
    LaunchedEffect(finished) { if (finished) Sfx.win() }
    val fade = remember { Animatable(1f) }
    val badge = listOf("أ", "ب", "ج", "د", "هـ")
    DisposableEffect(Unit) { onDispose { pl.stop() } }
    LaunchedEffect(step) {
        pl.stop()
        pl.speed = st.speed
        queue.getOrNull(step)?.takeIf { it.listen && st.autoPlay }?.let { q ->
            audioRefs[q.verse]?.let { pl.play(it, audioRanges[q.verse]) }
        }
    }
    LaunchedEffect(step) { fade.snapTo(0f); fade.animateTo(1f, tween(300)) }

    Column(Modifier.fillMaxSize().background(Cream).statusBarsPadding()) {
        Row(Modifier.fillMaxWidth().padding(16.dp), verticalAlignment = Alignment.CenterVertically) {
            T("✕", 22, FontWeight.Bold, Muted, m = Modifier.clickable { onExit(null) })
            Spacer(Modifier.width(12.dp))
            Box(Modifier.weight(1f)) { Bar(if (step < 0) 0f else step / queue.size.toFloat(), Green, 14.dp) }
            Spacer(Modifier.width(12.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                if (combo >= 2) { T("🔥$combo", 16, FontWeight.Bold, GoldDark); Spacer(Modifier.width(8.dp)) }
                if (maxHearts > 3) T("∞", 22, FontWeight.Bold, GreenT)
                else repeat(3) { T(if (it < hearts) "❤️" else "🖤", 18) }
            }
        }
        when {
            hearts == 0 && !checked -> Column(Modifier.weight(1f).padding(24.dp), Arrangement.Center, Alignment.CenterHorizontally) {
                T("نفدت القلوب 💔", 28, FontWeight.Bold, Red)
                T("راجع الشرح ثم حاول من جديد.", 18, m = Modifier.padding(vertical = 16.dp))
                Btn("رجوع") { onExit(null) }
            }
            step == -1 -> {
                Column(Modifier.weight(1f).verticalScroll(rememberScrollState()).padding(24.dp), verticalArrangement = Arrangement.spacedBy(16.dp)) {
                    T(l.title, 32, FontWeight.Bold, GreenT)
                    Box(Modifier.card()) { T(l.intro, 19) }
                    if (l.opts.isNotEmpty()) T("الأحكام في هذا الدرس", 17, FontWeight.Bold, GoldDark)
                    l.opts.forEach {
                        Box(Modifier.fillMaxWidth().clip(RoundedCornerShape(14.dp)).background(GoldSoft)
                            .padding(horizontal = 16.dp, vertical = 6.dp)) { T("✦  $it", 18, FontWeight.Medium, GoldDark) }
                    }
                }
                Btn("ابدأ", m = Modifier.fillMaxWidth().navigationBarsPadding().padding(16.dp)) { step = 0 }
            }
            step >= queue.size -> {
                val stars = if (mistakes == 0) 3 else if (mistakes <= 2) 2 else 1
                Box(Modifier.weight(1f)) {
                    Confetti()
                    Column(Modifier.fillMaxSize().padding(24.dp), Arrangement.Center, Alignment.CenterHorizontally) {
                        T("أحسنت! 🎉", 32, FontWeight.Bold, GreenT)
                        T(l.title, 20, FontWeight.Medium, GoldDark)
                        Spacer(Modifier.height(16.dp))
                        PopStars(stars)
                        Spacer(Modifier.height(16.dp))
                        Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                            Box(Modifier.clip(RoundedCornerShape(14.dp)).background(Surface).border(2.dp, Grey, RoundedCornerShape(14.dp)).padding(horizontal = 18.dp, vertical = 6.dp)) {
                                T("+${stars * perStar} نقطة", 18, FontWeight.Bold, GoldDark) }
                            Box(Modifier.clip(RoundedCornerShape(14.dp)).background(Surface).border(2.dp, Grey, RoundedCornerShape(14.dp)).padding(horizontal = 18.dp, vertical = 6.dp)) {
                                T("أخطاء: $mistakes", 18, FontWeight.Bold, if (mistakes == 0) GreenT else Red) }
                        }
                    }
                }
                Btn("متابعة", m = Modifier.fillMaxWidth().navigationBarsPadding().padding(16.dp)) { onExit(stars) }
            }
            else -> {
                val q = queue[step]
                val ok = checked && sel == q.answers
                Column(Modifier.weight(1f).graphicsLayer { alpha = fade.value; translationX = shake.value }.verticalScroll(rememberScrollState())
                    .padding(horizontal = 20.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    T(q.prompt, 21, FontWeight.Bold)
                    if (q.verse.isNotEmpty()) Column(Modifier.card(), horizontalAlignment = Alignment.CenterHorizontally) {
                        Verse(q.verse, if (checked) q.marks else emptyList(), if (q.listen) 28 else 40, GreenT)
                        if (checked && q.marks.isNotEmpty()) T("الحروف الملوّنة هي موضع الحكم", 14, FontWeight.Medium, Red, TextAlign.Center, Modifier.fillMaxWidth())
                        audioRefs[q.verse]?.let { ref ->
                            Spacer(Modifier.height(8.dp))
                            Box(Modifier.clip(CircleShape).background(if (pl.busy) Gold else Soft)
                                .clickable { if (pl.busy) pl.stop() else { pl.speed = st.speed; pl.play(ref, audioRanges[q.verse]) } }
                                .padding(horizontal = 18.dp, vertical = 8.dp)) {
                                T(if (pl.busy) "⏹ إيقاف" else "🔊 استمع للمثال", 16, FontWeight.Medium, if (pl.busy) Color(0xFF2B2B2B) else GreenT)
                            }
                            if (pl.note.isNotEmpty()) T("تعذّر اقتطاع المثال فشُغّلت الآية كاملة (${pl.note})", 12, c = Muted, m = Modifier.padding(top = 6.dp))
                            if (pl.error) T("تعذّر التشغيل، تحقق من الاتصال بالإنترنت", 14, c = Red, m = Modifier.padding(top = 6.dp))
                        }
                    }
                    if (q.multi && !checked) T("يمكنك اختيار أكثر من إجابة", 15, FontWeight.Medium, Muted)
                    if (q.listen && !checked) {
                        if (hint) T("💡 " + q.hint, 17, FontWeight.Medium, GoldDark)
                        else Box(Modifier.clip(CircleShape).background(GoldSoft).clickable { hint = true }
                            .padding(horizontal = 18.dp, vertical = 8.dp)) { T("💡 تلميح", 16, FontWeight.Medium, GoldDark) }
                    }
                    q.opts.forEachIndexed { i, o ->
                        val r = RoundedCornerShape(16.dp)
                        val right = i in q.answers; val picked = i in sel
                        val bg = when { checked && right -> OkBg; checked && picked -> BadBg; picked -> Soft; else -> Surface }
                        val bc = when { checked && right -> Green; checked && picked -> Red; picked -> Green; else -> Grey }
                        val sc by animateFloatAsState(if (picked && !checked) 1.02f else 1f, label = "opt$i")
                        Row(Modifier.fillMaxWidth().graphicsLayer { scaleX = sc; scaleY = sc }
                            .clip(r).background(bg).border(2.dp, bc, r)
                            .clickable(enabled = !checked) { sel = if (q.multi) (if (picked) sel - i else sel + i) else setOf(i) }.padding(14.dp),
                            verticalAlignment = Alignment.CenterVertically) {
                            Box(Modifier.size(34.dp).clip(CircleShape).background(if (bc == Grey) Off else bc), Alignment.Center) {
                                T(badge.getOrElse(i) { "" }, 15, FontWeight.Bold, if (bc == Grey) Muted else Color.White, TextAlign.Center)
                            }
                            Spacer(Modifier.width(12.dp))
                            T(o, if (q.verse.isEmpty()) 24 else 20, FontWeight.Medium)
                        }
                    }
                    Spacer(Modifier.height(8.dp))
                }
                Column(Modifier.fillMaxWidth()
                    .clip(RoundedCornerShape(topStart = 24.dp, topEnd = 24.dp))
                    .background(if (!checked) Surface else if (ok) OkBg else BadBg)
                    .navigationBarsPadding().padding(16.dp)) {
                    if (checked) {
                        T(
                            if (ok) (if (combo >= 3) "أحسنت! ✓  🔥 $combo إجابات متتالية" else "أحسنت! ✓")
                            else if (q.multi) "الأمثلة الصحيحة: " + q.answers.sorted().joinToString("، ") { q.opts[it] }
                            else "الإجابة الصحيحة: " + q.opts[q.ans],
                            19, FontWeight.Bold, if (ok) GreenT else Red
                        )
                        T("الشرح", 15, FontWeight.Bold, GoldDark, m = Modifier.padding(top = 6.dp))
                        Box(Modifier.heightIn(max = 220.dp).verticalScroll(rememberScrollState()).padding(bottom = 12.dp)) {
                            T(q.why, 17)
                        }
                        st.daysUntilReview(q.key)?.let { n ->
                            T("🧠 " + (if (n <= 0) "سيظهر في مراجعة اليوم" else if (n == 1) "سيعود للمراجعة غدًا" else if (n == 2) "سيعود للمراجعة بعد يومين" else if (n <= 10) "سيعود للمراجعة بعد $n أيام" else "سيعود للمراجعة بعد $n يومًا"),
                                14, FontWeight.Medium, GreenT, m = Modifier.padding(bottom = 10.dp))
                        }
                        Btn("التالي", if (ok) Green else Red, if (ok) GreenDark else Color(0xFFA9322A)) {
                            step++; sel = emptySet(); checked = false; hint = false
                        }
                    } else Btn("تحقق", on = sel.isNotEmpty()) {
                        checked = true
                        pl.stop()
                        if (q.key.isNotEmpty()) {
                            st.record(q.key, sel == q.answers)
                            if (failed.add(q.key)) st.srsAnswer(q.key, sel == q.answers)
                        }
                        if (sel != q.answers) {
                            combo = 0; Sfx.wrong()
                            mistakes++; hearts--; queue.add(q)
                            haptic.performHapticFeedback(HapticFeedbackType.LongPress)
                        } else {
                            combo++; Sfx.correct(combo)
                            haptic.performHapticFeedback(HapticFeedbackType.TextHandleMove)
                        }
                    }
                }
            }
        }
    }
}
